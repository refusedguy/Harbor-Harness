using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Harbor.CodeGen;

[Generator]
public sealed class EscapeCodeGenerator : IIncrementalGenerator
{
    // Matched by metadata name (not by type reference) so this netstandard2.0
    // Roslyn component needs no project reference. Must track the attribute in
    // src/Harbor.Abstractions.Contracts/TerminalEscapeAttribute.cs.
    private const string AttributeName = "TerminalEscapeAttribute";
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var enumSymbols = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => node is Microsoft.CodeAnalysis.CSharp.Syntax.EnumDeclarationSyntax,
                transform: static (ctx, _) => (INamedTypeSymbol)ctx.SemanticModel.GetDeclaredSymbol(ctx.Node)!)
            .Where(static e => e.GetAttributes().Any(ad => ad.AttributeClass?.Name == AttributeName))
            .Select(static (enumSymbol, _) =>
            {
                var enumName = enumSymbol.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat);
                var @namespace = enumSymbol.ContainingNamespace.ToDisplayString();

                var attrData = enumSymbol.GetAttributes()
                    .FirstOrDefault(ad => ad.AttributeClass?.Name == AttributeName);
                string className = $"{enumName}EscapeCodes";
                string? ns = null;
                string resetMember = "Reset";

                if (attrData is not null)
                {
                    foreach (var na in attrData.NamedArguments)
                    {
                        switch (na.Key)
                        {
                            case "ClassName":
                                className = na.Value.Value?.ToString() ?? className;
                                break;
                            case "Namespace":
                                ns = na.Value.Value?.ToString();
                                break;
                            case "ResetMember":
                                resetMember = na.Value.Value?.ToString() ?? resetMember;
                                break;
                        }
                    }
                }

                var members = enumSymbol.GetMembers()
                    .OfType<IFieldSymbol>()
                    .Where(f => f.HasConstantValue && f.ConstantValue is byte or sbyte or short or int)
                    .Select(f => (Name: f.Name, Value: Convert.ToByte(f.ConstantValue)))
                    .OrderBy(m => m.Value)
                    .ToArray();

                return (
                    EnumName: enumName,
                    Namespace: ns ?? @namespace,
                    ClassName: className,
                    ResetMember: resetMember,
                    Members: members,
                    Kind: DetectKind(enumName)
                );
            })
            .Where(static data => data.Members.Length > 0);

        context.RegisterSourceOutput(enumSymbols, static (spc, data) =>
        {
            spc.AddSource($"EscapeCodes_{Sanitize(data.Namespace)}_{data.ClassName}.g.cs", SourceText.From(GenerateClass(data), Encoding.UTF8));
        });
    }

    private static string Sanitize(string s) => s.Replace('.', '_').Replace('+', '_').Replace('<', '_').Replace('>', '_');

    private static EscapeKind DetectKind(string enumName) => enumName switch
    {
        "StyleFlag" => EscapeKind.Style,
        "CursorDirection" => EscapeKind.Cursor,
        "Color8Bit" => EscapeKind.Color8Bit,
        _ => EscapeKind.Generic
    };

    private enum EscapeKind { Style, Cursor, Color8Bit, Generic }

    private static string GenerateClass((string EnumName, string Namespace, string ClassName, string ResetMember, (string Name, byte Value)[] Members, EscapeKind Kind) data)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// EscapeCodeGenerator — DO NOT EDIT");
        sb.AppendLine($"namespace {data.Namespace};");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine($"///     Precomputed escape-code strings for <see cref=\"{data.EnumName}\" />.");
        sb.AppendLine("///     Generated by <see cref=\"EscapeCodeGenerator\" /> — zero allocations on hot paths.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class " + data.ClassName);
        sb.AppendLine("{");

        if (data.Kind == EscapeKind.Style)
        {
            GenerateStyleCode(sb, data);
        }
        else if (data.Kind == EscapeKind.Cursor)
        {
            GenerateCursorCode(sb, data);
        }
        else if (data.Kind == EscapeKind.Color8Bit)
        {
            GenerateColorCode(sb, data);
        }
        else
        {
            GenerateGenericCode(sb, data);
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void GenerateStyleCode(StringBuilder sb, (string EnumName, string Namespace, string ClassName, string ResetMember, (string Name, byte Value)[] Members, EscapeKind Kind) data)
    {
        sb.AppendLine("    // Precomputed SGR parameter strings");
        foreach (var m in data.Members)
        {
            if (m.Name == "Reset")
            {
                sb.AppendLine($"    public const string {m.Name} = \"\\x1b[0m\";");
            }
            else
            {
                sb.AppendLine($"    public const string {m.Name} = \"\\x1b[{m.Value}m\";");
            }
        }

        // The empty-flags sentinel is the zero-valued member when one exists
        // (Reset, None, …) — some enums (bitmask StyleFlag) have no Reset.
        // Falls back to the attribute's ResetMember, then to the first member.
        string zeroName = data.Members.FirstOrDefault(m => m.Value == 0).Name
            ?? data.Members.FirstOrDefault(m => m.Name == data.ResetMember).Name
            ?? data.Members[0].Name;

        sb.AppendLine();
        sb.AppendLine($"    /// <summary>Combine multiple <see cref=\"{data.EnumName}\" /> flags into one SGR sequence.</summary>");
        sb.AppendLine($"    public static string Combine({data.EnumName} flags)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (flags == 0) return " + zeroName + ";");
        sb.AppendLine("        var codes = new System.Text.StringBuilder(16);");
        sb.AppendLine("        bool first = true;");
        sb.AppendLine("        foreach (" + data.EnumName + " f in System.Enum.GetValues(typeof(" + data.EnumName + ")))");
        sb.AppendLine("        {");
        sb.AppendLine("            if (f == " + data.EnumName + "." + zeroName + ") continue;");
        sb.AppendLine("            if ((flags & f) == 0) continue;");
        sb.AppendLine("            if (!first) codes.Append(';');");
        sb.AppendLine("            codes.Append((int)f);");
        sb.AppendLine("            first = false;");
        sb.AppendLine("        }");
        sb.AppendLine("        return codes.Length == 0 ? " + zeroName + " : $\"\\x1b[{codes}m\";");
        sb.AppendLine("    }");
    }

    private static void GenerateCursorCode(StringBuilder sb, (string EnumName, string Namespace, string ClassName, string ResetMember, (string Name, byte Value)[] Members, EscapeKind Kind) data)
    {
        var csiMap = new Dictionary<string, byte>
        {
            ["Up"] = (byte)'A', ["Down"] = (byte)'B', ["Forward"] = (byte)'C',
            ["Back"] = (byte)'D', ["NextLine"] = (byte)'E', ["PreviousLine"] = (byte)'F',
            ["HorizontalAbsolute"] = (byte)'G', ["Position"] = (byte)'H',
            ["EraseDisplay"] = (byte)'J', ["EraseLine"] = (byte)'K',
            ["ScrollUp"] = (byte)'S', ["ScrollDown"] = (byte)'T',
            ["Save"] = (byte)'s', ["Restore"] = (byte)'u',
        };

        sb.AppendLine("    /// <summary>Build a CSI sequence for <paramref name=\"direction\" /> with optional <paramref name=\"count\" />.</summary>");
        sb.AppendLine("    public static string Cursor(CursorDirection direction, int count = 1)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (count <= 0) return string.Empty;");
        sb.AppendLine("        char final = direction switch");
        sb.AppendLine("        {");
        foreach (var m in data.Members.OrderBy(m => m.Value))
        {
            byte finalByte = csiMap.TryGetValue(m.Name, out byte found) ? found : (byte)' ';
            sb.AppendLine($"            {data.EnumName}.{m.Name} => '{(char)finalByte}',");
        }
        sb.AppendLine("            _ => ' '");
        sb.AppendLine("        };");
        sb.AppendLine("        return count == 1 ? $\"\\x1b[{final}\" : $\"\\x1b[{count}{final}\";");
        sb.AppendLine("    }");
    }

    private static void GenerateColorCode(StringBuilder sb, (string EnumName, string Namespace, string ClassName, string ResetMember, (string Name, byte Value)[] Members, EscapeKind Kind) data)
    {
        sb.AppendLine("    /// <summary>ESC [ 38;5;{n} m — set foreground to palette color.</summary>");
        sb.AppendLine("    public static string Foreground(Color8Bit color)");
        sb.AppendLine("    {");
        sb.AppendLine("        return color switch");
        sb.AppendLine("        {");
        foreach (var m in data.Members.OrderBy(m => m.Value))
        {
            sb.AppendLine($"            {data.EnumName}.{m.Name} => $\"\\x1b[38;5;{(int)m.Value}m\",");
        }
        sb.AppendLine("            _ => $\"\\x1b[38;5;{(int)color}m\"");
        sb.AppendLine("        };");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>ESC [ 48;5;{n} m — set background to palette color.</summary>");
        sb.AppendLine("    public static string Background(Color8Bit color)");
        sb.AppendLine("    {");
        sb.AppendLine("        return color switch");
        sb.AppendLine("        {");
        foreach (var m in data.Members.OrderBy(m => m.Value))
        {
            sb.AppendLine($"            {data.EnumName}.{m.Name} => $\"\\x1b[48;5;{(int)m.Value}m\",");
        }
        sb.AppendLine("            _ => $\"\\x1b[48;5;{(int)color}m\"");
        sb.AppendLine("        };");
        sb.AppendLine("    }");
    }

    private static void GenerateGenericCode(StringBuilder sb, (string EnumName, string Namespace, string ClassName, string ResetMember, (string Name, byte Value)[] Members, EscapeKind Kind) data)
    {
        foreach (var m in data.Members)
        {
            sb.AppendLine($"    public const string {m.Name} = \"\\x1b[{(m.Value == 0 ? 0 : m.Value)}m\";");
        }
    }
}
