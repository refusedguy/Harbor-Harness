using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Harbor.CodeGen;

/// <summary>
///     Generates a mood→frame dispatch class from enums annotated with
///     <c>[MoodFrame]</c>.
/// </summary>
/// <remarks>
///     <para>
///         The attribute lists the moods that participate in frame dispatch;
///         frame banks are resolved by naming convention — a static
///         <c>{Mood}Frames</c> field on the type named
///         <see cref="MoodFrameAttribute.BankContainer" /> (or at the enum's
///         own namespace level when the container is empty). The generated
///         static class <c>{EnumName}Frames</c> replaces the hand-written
///         <c>switch</c> dispatch with a single generated source of truth.
///     </para>
///     <para>
///         Zero allocations: the dispatch returns references to static
///         <c>string[]</c> banks (never copied), the tick→index math is pure
///         arithmetic, and no LINQ/reflection is involved at runtime —
///         AOT-safe by construction. The <see cref="MoodFrameAttribute.SleepPeriodTicks" />
///         special case applies to the member named <c>Sleeping</c>: it
///         advances one frame per N ticks instead of every tick.
///     </para>
/// </remarks>
[Generator]
public sealed class MoodFrameGenerator : IIncrementalGenerator
{
    private const string AttributeName = "Harbor.CodeGen.MoodFrameAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var enums = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeName,
            static (node, _) => node is EnumDeclarationSyntax,
            static (ctx, _) => MoodFrameInfo.Create((INamedTypeSymbol)ctx.TargetSymbol));

        context.RegisterSourceOutput(enums, static (spc, info) => Emit(spc, info));
    }

    private static void Emit(SourceProductionContext spc, MoodFrameInfo info)
    {
        if (info.Moods.Length == 0)
        {
            return;
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Generated by Harbor.CodeGen.MoodFrameGenerator from [MoodFrame] on " + info.EnumName + ".");
        sb.AppendLine("// Mood → frame-bank dispatch table — do not edit; banks live on " + (info.BankContainer.Length > 0 ? info.BankContainer : "namespace-level statics") + ".");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        if (info.Namespace.Length > 0)
        {
            sb.AppendLine($"namespace {info.Namespace};");
            sb.AppendLine();
        }

        sb.AppendLine($"/// <summary>Generated dispatch table for <see cref=\"{info.EnumName}\"/> mood frame banks.</summary>");
        sb.AppendLine($"public static class {info.EnumName}Frames");
        sb.AppendLine("{");

        EmitFramesOf(sb, info);
        EmitFrameIndex(sb, info);
        EmitFrame(sb, info);
        EmitFrameCount(sb, info);

        sb.AppendLine("}");

        spc.AddSource($"MoodFrames_{info.EnumName}.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static string Bank(MoodFrameInfo info, string mood) => info.BankContainer.Length > 0
        ? $"{info.BankContainer}.{mood}Frames"
        : $"{mood}Frames";

    private static void EmitFramesOf(StringBuilder sb, MoodFrameInfo info)
    {
        sb.AppendLine($"    /// <summary>Frame bank for a mood — static arrays, never copied.</summary>");
        sb.AppendLine($"    public static string[] FramesOf({info.EnumName} mood) => mood switch");
        sb.AppendLine("    {");
        foreach (string mood in info.Moods)
        {
            sb.AppendLine($"        {info.EnumName}.{mood} => {Bank(info, mood)},");
        }

        sb.AppendLine($"        _ => {Bank(info, info.Moods[0])},");
        sb.AppendLine("    };");
        sb.AppendLine();
    }

    private static void EmitFrameIndex(StringBuilder sb, MoodFrameInfo info)
    {
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Index into the mood's frame bank for the given monotonic tick.");
        sb.AppendLine("    /// Deterministic; negative ticks wrap. The mood named \"Sleeping\"");
        sb.AppendLine($"    /// advances one frame per {info.SleepPeriodTicks} ticks" + (info.SleepPeriodTicks > 0 ? "." : " (disabled — period 1)."));
        sb.AppendLine("    /// </summary>");
        sb.AppendLine($"    public static int FrameIndex(long monotonicTick, {info.EnumName} mood)");
        sb.AppendLine("    {");
        sb.AppendLine("        string[] frames = FramesOf(mood);");

        if (info.SleepPeriodTicks > 0 && info.SleepingMood is not null)
        {
            sb.AppendLine($"        long period = mood == {info.EnumName}.{info.SleepingMood} ? {info.SleepPeriodTicks} : 1;");
        }
        else
        {
            sb.AppendLine("        long period = 1;");
        }

        sb.AppendLine("        int i = (int)((monotonicTick / period) % frames.Length);");
        sb.AppendLine("        return i >= 0 ? i : i + frames.Length;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static void EmitFrame(StringBuilder sb, MoodFrameInfo info)
    {
        sb.AppendLine("    /// <summary>Frame for the given monotonic tick and mood. Deterministic.</summary>");
        sb.AppendLine($"    public static string Frame(long monotonicTick, {info.EnumName} mood)");
        sb.AppendLine("        => FramesOf(mood)[FrameIndex(monotonicTick, mood)];");
        sb.AppendLine();
    }

    private static void EmitFrameCount(StringBuilder sb, MoodFrameInfo info)
    {
        sb.AppendLine("    /// <summary>Number of frames in the mood's bank.</summary>");
        sb.AppendLine($"    public static int FrameCount({info.EnumName} mood) => FramesOf(mood).Length;");
        sb.AppendLine();
    }
}

/// <summary>Equatable snapshot of a [MoodFrame] enum for the incremental pipeline.</summary>
internal sealed class MoodFrameInfo : IEquatable<MoodFrameInfo>
{
    public MoodFrameInfo(
        string enumName,
        string ns,
        ImmutableArray<string> moods,
        string bankContainer,
        int sleepPeriodTicks)
    {
        EnumName = enumName;
        Namespace = ns;
        Moods = moods;
        BankContainer = bankContainer;
        SleepPeriodTicks = sleepPeriodTicks;
        SleepingMood = moods.FirstOrDefault(static m => m == "Sleeping");
    }

    public string EnumName { get; }

    public string Namespace { get; }

    public ImmutableArray<string> Moods { get; }

    public string BankContainer { get; }

    public int SleepPeriodTicks { get; }

    public string? SleepingMood { get; }

    public bool Equals(MoodFrameInfo? other) =>
        other is not null
        && EnumName == other.EnumName
        && Namespace == other.Namespace
        && Moods.SequenceEqual(other.Moods)
        && BankContainer == other.BankContainer
        && SleepPeriodTicks == other.SleepPeriodTicks;

    public override bool Equals(object? obj) => Equals(obj as MoodFrameInfo);

    public override int GetHashCode()
    {
        unchecked
        {
            int hash = EnumName.GetHashCode() * 397;
            hash ^= Namespace.GetHashCode();
            hash = (hash * 31) ^ BankContainer.GetHashCode();
            hash = (hash * 31) ^ SleepPeriodTicks;
            foreach (string mood in Moods)
            {
                hash = (hash * 31) ^ mood.GetHashCode();
            }

            return hash;
        }
    }

    public static MoodFrameInfo Create(INamedTypeSymbol enumSymbol)
    {
        AttributeData? attr = enumSymbol
            .GetAttributes()
            .FirstOrDefault(static a => a.AttributeClass?.ToDisplayString() == "Harbor.CodeGen.MoodFrameAttribute");
        if (attr is null)
        {
            return new MoodFrameInfo(
                enumSymbol.Name,
                enumSymbol.ContainingNamespace.ToDisplayString(),
                ImmutableArray<string>.Empty,
                string.Empty,
                0);
        }

        // Moods arrive as a params object[] constructor argument — a
        // TypedConstant array of enum constants (values), mapped back to
        // member names via the enum symbol's constant fields.
        var valueToName = new Dictionary<long, string>();
        foreach (ISymbol member in enumSymbol.GetMembers())
        {
            if (member is IFieldSymbol { ConstantValue: not null } field)
            {
                valueToName[Convert.ToInt64(field.ConstantValue)] = field.Name;
            }
        }

        var moods = ImmutableArray.CreateBuilder<string>();
        if (attr.ConstructorArguments.Length > 0 && attr.ConstructorArguments[0].Kind == TypedConstantKind.Array)
        {
            foreach (TypedConstant arg in attr.ConstructorArguments[0].Values)
            {
                if (arg.Value is null)
                {
                    continue;
                }

                if (valueToName.TryGetValue(Convert.ToInt64(arg.Value), out string? name) && !moods.Contains(name))
                {
                    moods.Add(name);
                }
            }
        }

        string bankContainer = string.Empty;
        int sleepPeriodTicks = 0;
        foreach (KeyValuePair<string, TypedConstant> named in attr.NamedArguments)
        {
            if (named.Key == "BankContainer" && named.Value.Value is string container)
            {
                bankContainer = container;
            }
            else if (named.Key == "SleepPeriodTicks" && named.Value.Value is int period)
            {
                sleepPeriodTicks = period;
            }
        }

        return new MoodFrameInfo(
            enumSymbol.Name,
            enumSymbol.ContainingNamespace.ToDisplayString(),
            moods.ToImmutable(),
            bankContainer,
            sleepPeriodTicks);
    }
}
