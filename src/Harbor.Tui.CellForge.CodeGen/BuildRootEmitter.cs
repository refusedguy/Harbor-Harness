using System;
using System.Collections.Generic;
using System.Globalization;
using Harbor.Abstractions.Dsl;

namespace Harbor.Tui.CellForge.CodeGen;

/// <summary>
///     Emits the two source halves of a generated root builder: the phase-1
///     declarations and the phase-2 <c>BuildRoot</c> method. It reads only the
///     shared <see cref="SpecArena"/> IR, so no second markup parser exists.
/// </summary>
/// <remarks>
///     Every <c>Begin</c> and <c>Text</c> call carries a dense, local sequence
///     number assigned in pre-order. The consumer uses that number as the
///     cell-diff key, the same role a Blazor render-tree frame sequence plays.
/// </remarks>
internal static class BuildRootEmitter
{
    /// <summary>Hint name of the shared root-builder contract.</summary>
    internal const string RootContractHintName = "CellForgeRootContract.g.cs";

    private const string Namespace = "Harbor.Tui.CellForge.CodeGen.Generated";
    private const string NewOperation = "new";

    /// <summary>
    ///     The contract added to the compilation during post-initialization,
    ///     before any per-file source is generated. It declares the type of the
    ///     <c>root</c> parameter that every <c>BuildRoot</c> binds against.
    /// </summary>
    internal static string RootContract() => Lines(
        "// <auto-generated/>",
        "// #2428 phase 1: the root-builder contract is in the compilation",
        "// before any per-file declaration or BuildRoot is generated.",
        $"namespace {Namespace};",
        "",
        "/// <summary>",
        "///     Receives the sequence-numbered calls emitted by a generated",
        "///     <c>BuildRoot</c>. A sequence is the stable cell-diff key, the",
        "///     role a Blazor render-tree frame sequence plays.",
        "/// </summary>",
        "internal interface ICellForgeRoot",
        "{",
        "    /// <summary>Opens a node; <c>sequence</c> keys its frame.</summary>",
        "    void Begin(int sequence);",
        "",
        // #2438: the declared .id is a test locator carried by the real tree.
        "    /// <summary>Attaches the declared test locator to a node frame.</summary>",
        "    void TestId(int sequence, string testId);",
        "",
        "    /// <summary>Writes text; <c>sequence</c> keys its frame.</summary>",
        "    void Text(int sequence, string text);",
        "",
        "    /// <summary>Closes the most recently opened node.</summary>",
        "    void End();",
        "}");

    /// <summary>
    ///     Phase 1 for one markup file: the partial class and its parameter
    ///     declarations. This source lands in the compilation before phase 2.
    /// </summary>
    internal static string EmitDeclaration(
        string targetPath,
        string identifier,
        MarkupParseResult parse,
        string checksum)
    {
        var lines = new List<string>
        {
            "// <auto-generated/>",
            "// #2428 phase 1: declarations added to the compilation before",
            "// phase 2 emits BuildRoot.",
            "// #2431: the checksum travels with the code so dev mode can reject stale output.",
            $"namespace {Namespace};",
            "",
            $"internal partial class {identifier}",
            "{",
            $"    internal const string TargetPath = {Literal(targetPath)};",
            $"    internal const int RootCount = {Number(parse.Arena.Roots.Count)};",
            $"    internal const int SequenceCount = {Number(CountSequences(parse.Arena))};",
            $"    internal const string SourceChecksum = {Literal(checksum)};",
            // #2517: ids from .id operations reach the generated class through
            // SpecNode.Id, so a consumer can map a parsed node to a stable key.
            $"    internal static readonly string[] NodeIds = [{IdList(parse.Arena)}];",
        };

        // #2435: the Debug-only swap point. A null field runs the compiled
        // BuildRoot body; a non-null one replaces it without a new process.
        // Release/AOT compilations drop both the field and the check, so the
        // hook adds no dynamic code to the shipped binary.
        lines.Add("#if DEBUG");
        lines.Add("    /// <summary>#2435: dev-only override of this root's compiled body.</summary>");
        lines.Add("    internal static System.Action<System.Action<int>, System.Action<int, string>, System.Action>? BuildRootOverride;");
        lines.Add("#endif");

        // #2431: a comment per node and operation carries its 1-based source
        // position from the IR, so generated code points back to the markup.
        AppendPositionComments(lines, parse.Arena.Roots, 0);
        lines.Add("}");
        return Lines(lines.ToArray());
    }

    private static void AppendPositionComments(List<string> lines, IReadOnlyList<SpecNode> nodes, int depth)
    {
        var indent = new string(' ', 8 + depth * 2);
        foreach (var node in nodes)
        {
            lines.Add($"{indent}// node {node.Kind} @ {Number(node.SourceLine)}:{Number(node.SourceColumn)}");
            foreach (var operation in node.Operations)
            {
                lines.Add($"{indent}  // op {operation.Name} @ {Number(operation.SourceLine)}:{Number(operation.SourceColumn)}");
            }

            AppendPositionComments(lines, node.Children, depth + 1);
        }
    }

    /// <summary>
    ///     Phase 2 for one module: the <c>BuildRoot</c> half with dense local
    ///     sequence numbers plus an offset <c>BuildModule</c> half. Every
    ///     module gets both, so an importing screen can call the imported
    ///     builder directly without merging two files into one root.
    /// </summary>
    internal static string EmitBuildRootWithModules(
        string identifier,
        string modulePath,
        SpecArena arena,
        ResolvedModule module,
        ModuleGraphResult graph)
    {
        var body = new List<string>();
        var sequence = 0;
        foreach (var root in arena.Roots)
            EmitNode(root, body, ref sequence, false, modulePath, module, graph);

        var moduleBody = new List<string>();
        var moduleSequence = 0;
        foreach (var root in arena.Roots)
            EmitNode(root, moduleBody, ref moduleSequence, true, modulePath, module, graph);

        var lines = new List<string>
        {
            "// <auto-generated/>",
            "// #2428 phase 2: BuildRoot over the phase-1 declarations.",
            "// Sequence numbers are local, dense and assigned in pre-order;",
            "// cell-diff uses them as keys.",
            "// #3083: an imported module is called through its own builder,",
            "// never merged into another module's source.",
            $"namespace {Namespace};",
            "",
            $"internal partial class {identifier}",
            "{",
            "    /// <summary>Builds the root cell tree for <see cref=\"TargetPath\"/>.</summary>",
            "    internal static void BuildRoot(ICellForgeRoot root)",
            "    {",
            "#if DEBUG",
            "        // #2435: the per-root field wins; the shared slot lets the",
            "        // dev tooling swap the body without touching the host.",
            "        var devOverride = BuildRootOverride",
            "            ?? global::Harbor.Abstractions.Dsl.RootBuilderOverride.Current;",
            "        if (devOverride is not null)",
            "        {",
            "            devOverride(root.Begin, root.Text, root.End);",
            "            return;",
            "        }",
            "#endif",
        };
        lines.AddRange(body);
        lines.Add("    }");
        lines.Add("");
        lines.Add("    /// <summary>Builds this module's subtree at a caller-supplied sequence offset.</summary>");
        lines.Add("    internal static void BuildModule(ICellForgeRoot root, int baseSequence)");
        lines.Add("    {");
        lines.AddRange(moduleBody);
        lines.Add("    }");
        lines.AddRange(SpecLayoutEmitter.EmitMethod(arena));
        lines.Add("}");
        return Lines(lines.ToArray());
    }

    /// <summary>
    ///     Emits one node. With <paramref name="offset"/> the sequence argument
    ///     is relative to <c>baseSequence</c>, which is how an importing screen
    ///     calls this module's builder without colliding on cell-diff keys.
    ///     The single case and the graph case share this one traversal.
    /// </summary>
    private static void EmitNode(
        SpecNode node,
        List<string> body,
        ref int sequence,
        bool offset,
        string? modulePath,
        ResolvedModule? module,
        ModuleGraphResult? graph)
    {
        var begin = sequence++;
        body.Add($"        root.Begin({Sequence(begin, offset)}); // {node.Kind}, line {Number(node.SourceLine)}");

        // #2438: a declared .id reaches the automation protocol as testId
        // through this call, so the locator lives in BuildRoot itself.
        if (node.Id is not null)
            body.Add($"        root.TestId({Sequence(begin, offset)}, {Literal(node.Id)}); // testId, line {Number(node.SourceLine)}");

        if (node.Kind == SpecKind.Text)
        {
            var text = FirstArgument(node);
            body.Add($"        root.Text({Sequence(sequence++, offset)}, {Literal(text)}); // {node.Kind}, line {Number(node.SourceLine)}");
        }

        // #3083: `.use "path"` instantiates an imported module. The imported
        // builder is a separate generated class; its sequence range is
        // reserved here so cell-diff keys stay unique across the whole screen.
        if (modulePath is not null && module is not null && graph is not null)
        {
            foreach (var operation in node.Operations)
            {
                if (!string.Equals(operation.Name, "use", StringComparison.OrdinalIgnoreCase)
                    || operation.Arguments.Count == 0)
                    continue;

                var raw = operation.Arguments[0].Text;
                var target = MarkupModuleResolver.ResolveUse(modulePath, raw, module, graph.Identifiers);
                if (target is null)
                    continue;

                var targetIdentifier = graph.Identifiers[target];
                body.Add($"        {targetIdentifier}.BuildModule(root, {Sequence(sequence, offset)}); // use {Literal(raw)}, line {Number(operation.SourceLine)}");
                if (graph.SequenceCounts.TryGetValue(target, out var imported))
                    sequence += imported;
            }
        }

        foreach (var child in node.Children)
            EmitNode(child, body, ref sequence, offset, modulePath, module, graph);

        body.Add($"        root.End(); // {node.Kind}, line {Number(node.SourceLine)}");
    }

    private static string Sequence(int value, bool offset) =>
        offset ? "baseSequence + " + Number(value) : Number(value);

    /// <summary>Counts the numbers a traversal will hand out: one per Begin and one per Text.</summary>
    private static int CountSequences(SpecArena arena)
    {
        var count = 0;
        foreach (var root in arena.Roots)
            CountNode(root, ref count);
        return count;
    }

    private static void CountNode(SpecNode node, ref int count)
    {
        count++;
        if (node.Kind == SpecKind.Text)
            count++;
        foreach (var child in node.Children)
            CountNode(child, ref count);
    }

    /// <summary>The first literal recorded by a node's <c>new</c> operation, if any.</summary>
    private static string FirstArgument(SpecNode node)
    {
        foreach (var operation in node.Operations)
        {
            if (!string.Equals(operation.Name, NewOperation, StringComparison.Ordinal))
                continue;
            if (operation.Arguments.Count > 0)
                return operation.Arguments[0].Text;
        }

        return string.Empty;
    }

    /// <summary>Quoted ids from the arena, in node order, for the generated class.</summary>
    private static string IdList(SpecArena arena)
    {
        var ids = new List<string>();
        foreach (var node in arena.Nodes)
        {
            if (node.Id is not null)
                ids.Add(Literal(node.Id));
        }

        return string.Join(", ", ids);
    }

    internal static string Literal(string value) => EmittedCSharp.StringLiteral(value);

    private static string Number(int value) => value.ToString(CultureInfo.InvariantCulture);

    private static string Lines(params string[] lines) => string.Join("\n", lines) + "\n";
}

/// <summary>Phase-1 output for one file. All fields are value-comparable.</summary>
internal sealed record DeclarationInput(string TargetPath, string Text, string Identifier);
