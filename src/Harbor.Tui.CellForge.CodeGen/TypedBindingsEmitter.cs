using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Harbor.Abstractions.Dsl;
using Microsoft.CodeAnalysis;

namespace Harbor.Tui.CellForge.CodeGen;

/// <summary>
///     Resolves <c>{Binding ...}</c> paths against the type named by a
///     <c>state:</c> directive and emits typed delegates for them.
/// </summary>
/// <remarks>
///     Symbol resolution happens here, at build time, through Roslyn. The
///     emitted source contains direct property access inside static lambdas:
///     no reflection, no <c>dynamic</c>, no IL emit. That is what keeps the
///     update path AOT-safe (IL2026) once the generated delegates run.
/// </remarks>
internal static class TypedBindingsEmitter
{
    private const string Namespace = "Harbor.Tui.CellForge.CodeGen.Generated";
    private const string BindingPrefix = "{Binding ";
    private const string TwoWayOption = "Mode=TwoWay";

    /// <summary>
    ///     Resolves the bindings of one markup file and returns the source to
    ///     emit plus any errors that must break the build.
    /// </summary>
    internal static BindingsOutput Emit(
        Compilation compilation,
        string targetPath,
        string identifier,
        string text,
        MarkupParseResult parse)
    {
        // A file with syntax errors already has HUI001 diagnostics from the
        // declarations phase. Do not stack binding errors on a broken tree.
        if (!parse.IsValid)
            return Empty(identifier, targetPath);

        var bindings = CollectBindings(parse.Arena, text);
        if (bindings.Count == 0)
            return Empty(identifier, targetPath);

        var diagnostics = new List<BindingDiagnosticData>();

        // Acceptance: a binding without state: Type breaks the build.
        if (parse.StateType is null)
        {
            var first = bindings[0];
            diagnostics.Add(new BindingDiagnosticData(
                "HUI002",
                $"Binding '{first.Path}' needs a 'state: Type' annotation.",
                first.Line,
                first.Column));
            return Failed(identifier, targetPath, diagnostics);
        }

        var stateType = ResolveStateType(compilation, parse.StateType);
        if (stateType is null)
        {
            diagnostics.Add(new BindingDiagnosticData(
                "HUI003",
                $"State type '{parse.StateType}' was not found in the compilation.",
                parse.StateTypeLine,
                1));
            return Failed(identifier, targetPath, diagnostics);
        }

        var stateDisplay = stateType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var members = new List<string>();

        foreach (var binding in bindings)
        {
            var resolution = ResolvePath(stateType, binding.Path);
            if (resolution.Error is not null)
            {
                diagnostics.Add(new BindingDiagnosticData(
                    "HUI004",
                    $"Property path '{binding.Path}' is invalid on state type '{parse.StateType}': {resolution.Error}",
                    binding.Line,
                    binding.Column));
                continue;
            }

            var valueDisplay = resolution.ValueType!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var name = MakeMemberName(binding.Path);
            members.Add(
                $"    internal static readonly global::System.Func<{stateDisplay}, {valueDisplay}> {name}_Get = static ({stateDisplay} s) => s.{resolution.CSharpPath};");

            if (!binding.TwoWay)
                continue;

            if (!resolution.CanWrite)
            {
                diagnostics.Add(new BindingDiagnosticData(
                    "HUI005",
                    $"Property path '{binding.Path}' cannot be written by a two-way binding.",
                    binding.Line,
                    binding.Column));
                continue;
            }

            members.Add(
                $"    internal static readonly global::System.Action<{stateDisplay}, {valueDisplay}> {name}_Set = static ({stateDisplay} s, {valueDisplay} v) => s.{resolution.CSharpPath} = v;");
        }

        // A bad path never reaches emitted code: one broken member would
        // otherwise turn the generated source into a second, less useful
        // compile error. The HUI004/HUI005 diagnostics are the report.
        if (diagnostics.Count != 0)
            return Failed(identifier, targetPath, diagnostics);

        var lines = new List<string>
        {
            "// <auto-generated/>",
            "// #2429: typed bindings resolved against the state: annotation.",
            $"namespace {Namespace};",
            "",
            $"internal static class {identifier}Bindings",
            "{",
            $"    internal const string StateType = {Literal(parse.StateType)};",
            "",
        };
        lines.AddRange(members);
        lines.Add("}");

        return new BindingsOutput(
            identifier,
            targetPath,
            Lines(lines.ToArray()),
            new EquatableArray<BindingDiagnosticData>([]));
    }

    private static BindingsOutput Empty(string identifier, string targetPath) =>
        new(identifier, targetPath, string.Empty, new EquatableArray<BindingDiagnosticData>([]));

    private static BindingsOutput Failed(
        string identifier,
        string targetPath,
        List<BindingDiagnosticData> diagnostics) =>
        new(identifier, targetPath, string.Empty, new EquatableArray<BindingDiagnosticData>(diagnostics));

    /// <summary>Walks the IR once and returns each binding with its source position.</summary>
    private static List<Binding> CollectBindings(SpecArena arena, string text)
    {
        var result = new List<Binding>();
        foreach (var node in arena.Nodes)
        {
            foreach (var operation in node.Operations)
            {
                foreach (var argument in operation.Arguments)
                {
                    if (argument.Kind != SpecValueKind.String
                        || !TryParseBinding(argument.Text, out var path, out var twoWay))
                        continue;

                    var (line, column) = FindPosition(text, node.SourceLine, argument.Text);
                    result.Add(new Binding(path, twoWay, line, column));
                }
            }
        }

        return result;
    }

    /// <summary>Reads <c>{Binding Path}</c> and <c>{Binding Path, Mode=TwoWay}</c>.</summary>
    private static bool TryParseBinding(string text, out string path, out bool twoWay)
    {
        path = string.Empty;
        twoWay = false;
        if (!text.StartsWith(BindingPrefix, StringComparison.Ordinal) || !text.EndsWith('}'))
            return false;

        var inside = text[BindingPrefix.Length..^1].Trim();
        var comma = inside.IndexOf(',');
        if (comma >= 0)
        {
            var options = inside[(comma + 1)..].Trim();
            inside = inside[..comma].Trim();
            twoWay = options
                .Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                .Any(option => option.Equals(TwoWayOption, StringComparison.OrdinalIgnoreCase));
        }

        if (inside.Length == 0)
            return false;

        path = inside;
        return true;
    }

    /// <summary>Locates the binding literal for the diagnostic, from the node's line onward.</summary>
    private static (int Line, int Column) FindPosition(string text, int sourceLine, string bindingText)
    {
        var lines = text.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n');
        for (var i = Math.Max(sourceLine - 1, 0); i < lines.Length; i++)
        {
            var index = lines[i].IndexOf(bindingText, StringComparison.Ordinal);
            if (index >= 0)
                return (i + 1, index + 1);
        }

        return (Math.Max(sourceLine, 1), 1);
    }

    /// <summary>Finds the annotated type in the compilation the generator sees.</summary>
    private static INamedTypeSymbol? ResolveStateType(Compilation compilation, string name)
    {
        var byMetadataName = compilation.GetTypeByMetadataName(name);
        if (byMetadataName is not null)
            return byMetadataName;

        // Source-declared types the markup names by simple or display name.
        var simpleName = name.Contains('.') ? name[(name.LastIndexOf('.') + 1)..] : name;
        foreach (var symbol in compilation.GetSymbolsWithName(simpleName, SymbolFilter.Type))
        {
            if (symbol is INamedTypeSymbol named
                && (string.Equals(named.ToDisplayString(), name, StringComparison.Ordinal)
                    || string.Equals(named.Name, name, StringComparison.Ordinal)))
                return named;
        }

        return null;
    }

    /// <summary>
    ///     Resolves every segment as a public readable property. The final
    ///     property's setter decides whether a two-way delegate can be emitted.
    /// </summary>
    private static PathResolution ResolvePath(INamedTypeSymbol stateType, string path)
    {
        var segments = path.Split('.');
        var properties = new List<IPropertySymbol>();
        ITypeSymbol current = stateType;

        foreach (var segment in segments)
        {
            if (segment.Length == 0)
                return new(null, string.Empty, "empty path segment", false);

            var property = current.GetMembers(segment)
                .OfType<IPropertySymbol>()
                .FirstOrDefault(candidate =>
                    candidate.GetMethod is { DeclaredAccessibility: Accessibility.Public });

            if (property is null)
                return new(
                    null,
                    string.Empty,
                    $"'{segment}' is not a readable public property of '{current.ToDisplayString()}'",
                    false);

            properties.Add(property);
            current = property.Type;
        }

        var last = properties[^1];
        var canWrite = last.SetMethod is { DeclaredAccessibility: Accessibility.Public };
        return new(current, string.Join(".", properties.Select(static p => p.Name)), null, canWrite);
    }

    private static string MakeMemberName(string path)
    {
        var result = new StringBuilder(path.Length);
        foreach (var c in path)
            result.Append(char.IsLetterOrDigit(c) ? c : '_');
        return result.Length == 0 ? "Binding" : result.ToString();
    }

    private static string Literal(string value)
    {
        var result = new StringBuilder(value.Length + 2);
        result.Append('"');
        foreach (var c in value)
        {
            switch (c)
            {
                case '\\': result.Append("\\\\"); break;
                case '"': result.Append("\\\""); break;
                case '\n': result.Append("\\n"); break;
                case '\r': result.Append("\\r"); break;
                case '\t': result.Append("\\t"); break;
                default:
                    if (char.IsControl(c))
                        result.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    else
                        result.Append(c);
                    break;
            }
        }

        result.Append('"');
        return result.ToString();
    }

    private static string Lines(params string[] lines) => string.Join("\n", lines) + "\n";

    private readonly record struct Binding(string Path, bool TwoWay, int Line, int Column);

    private readonly record struct PathResolution(
        ITypeSymbol? ValueType,
        string CSharpPath,
        string? Error,
        bool CanWrite);
}

/// <summary>One binding error: a diagnostic id, a message, and a markup position.</summary>
internal sealed record BindingDiagnosticData(string Id, string Message, int Line, int Column);

/// <summary>Phase-3 output for one file. Every field is value-comparable.</summary>
internal sealed record BindingsOutput(
    string Identifier,
    string TargetPath,
    string Source,
    EquatableArray<BindingDiagnosticData> Diagnostics);

/// <summary>
///     Sequence equality for the diagnostic array, so Roslyn's incremental
///     cache can detect an unchanged result across compilations.
/// </summary>
internal sealed class EquatableArray<T> : IEquatable<EquatableArray<T>>
{
    private readonly T[] _items;

    internal EquatableArray(IEnumerable<T> items) => _items = items.ToArray();

    internal IReadOnlyList<T> Items => _items;

    public bool Equals(EquatableArray<T>? other) =>
        other is not null && _items.SequenceEqual(other._items);

    public override bool Equals(object? obj) => Equals(obj as EquatableArray<T>);

    public override int GetHashCode()
    {
        var hash = new HashCode();
        foreach (var item in _items)
            hash.Add(item);
        return hash.ToHashCode();
    }
}
