using System;
using System.Collections.Generic;
using Harbor.Abstractions.Dsl;
using Microsoft.CodeAnalysis;

namespace Harbor.Tui.CellForge.CodeGen;

/// <summary>
///     Turns declarative <c>.bind "gesture" "action" "description"</c>
///     operations into <c>Binding</c> data for the consuming
///     compilation. The gesture stays a string in the markup; the generated
///     code parses it with the runtime's own <c>KeySpec</c>, so there is one
///     grammar for key specs and no reflection or IL emit on the hot path.
/// </summary>
/// <remarks>
///     The generator assembly has no reference to the runtime (see the
///     csproj). Emission is therefore gated on the binding type being present
///     in the consumer's compilation: a project without CellForge keeps
///     building, and a project with it gets a ready-to-register list.
/// </remarks>
internal static class KeyBindingsEmitter
{
    private const string BindingMetadataName = "Harbor.Tui.CellForge.Input.Binding";
    private const string Namespace = "Harbor.Tui.CellForge.CodeGen.Generated";
    private const string BindOperation = "bind";

    private const string BindingType = "global::Harbor.Tui.CellForge.Input.Binding";
    private const string BindingsMapType = "global::Harbor.Tui.CellForge.Input.BindingsMap";
    private const string KeySpecType = "global::Harbor.Tui.CellForge.Input.KeySpec";
    private const string ListType = "global::System.Collections.Generic.List<" + BindingType + ">";
    private const string ReadOnlyType = "global::System.Collections.Generic.IReadOnlyList<" + BindingType + ">";

    internal static KeyBindingsOutput Emit(
        Compilation compilation,
        string targetPath,
        string identifier,
        MarkupParseResult parse)
    {
        if (!parse.IsValid || compilation.GetTypeByMetadataName(BindingMetadataName) is null)
            return new(identifier, targetPath, string.Empty);

        var binds = CollectBinds(parse.Arena);
        if (binds.Count == 0)
            return new(identifier, targetPath, string.Empty);

        var lines = new List<string>
        {
            "// <auto-generated/>",
            "// #2688: declarative .bind operations become Binding data.",
            $"namespace {Namespace};",
            "",
            $"internal static class {identifier}KeyBindings",
            "{",
            $"    internal static {ReadOnlyType} Bindings {{ get; }} = Build();",
            "",
            "    /// <summary>Binds every declared binding into the supplied map.</summary>",
            $"    internal static void Register({BindingsMapType} map)",
            "    {",
            "        for (int i = 0; i < Bindings.Count; i++)",
            "            map.Bind(Bindings[i]);",
            "    }",
            "",
            $"    private static {ReadOnlyType} Build()",
            "    {",
            $"        var result = new {ListType}({binds.Count});",
        };

        foreach (KeyBinding bind in binds)
        {
            lines.Add("        Add(result, "
                + EmittedCSharp.StringLiteral(bind.Gesture) + ", "
                + EmittedCSharp.StringLiteral(bind.Action) + ", "
                + EmittedCSharp.StringLiteral(bind.Description) + ");");
        }

        lines.Add("        return result;");
        lines.Add("    }");
        lines.Add("");
        lines.Add($"    private static void Add({ListType} result, string spec, string action, string description)");
        lines.Add("    {");
        lines.Add($"        if (!{KeySpecType}.TryParse(spec, out var gesture))");
        lines.Add("            return;");
        lines.Add("");
        lines.Add($"        result.Add(new {BindingType}(action, gesture, action, description));");
        lines.Add("    }");
        lines.Add("}");

        return new(identifier, targetPath, string.Join("\n", lines) + "\n");
    }

    /// <summary>
    ///     Reads well-formed binds in source order. A malformed operation is
    ///     left out rather than emitting data that would throw when bound:
    ///     diagnostics for the DSL are a separate slice (#2431).
    /// </summary>
    private static List<KeyBinding> CollectBinds(SpecArena arena)
    {
        var result = new List<KeyBinding>();
        foreach (SpecNode node in arena.Nodes)
        {
            foreach (SpecOp operation in node.Operations)
            {
                if (!string.Equals(operation.Name, BindOperation, StringComparison.OrdinalIgnoreCase)
                    || operation.Arguments.Count < 2)
                    continue;

                string? gesture = Text(operation.Arguments, 0);
                string? action = Text(operation.Arguments, 1);
                if (gesture is null || action is null)
                    continue;

                string description = operation.Arguments.Count > 2
                    ? Text(operation.Arguments, 2) ?? string.Empty
                    : string.Empty;
                result.Add(new KeyBinding(gesture, action, description));
            }
        }

        return result;
    }

    private static string? Text(IReadOnlyList<SpecValue> arguments, int index)
    {
        SpecValue argument = arguments[index];
        return argument.Kind == SpecValueKind.String && argument.Text.Length != 0
            ? argument.Text
            : null;
    }

    private readonly record struct KeyBinding(string Gesture, string Action, string Description);
}

/// <summary>Phase-4 output for one file. Every field is value-comparable.</summary>
internal sealed record KeyBindingsOutput(string Identifier, string TargetPath, string Source);
