#!/usr/bin/env python3
"""Generate the agent-facing documentation entries at the repository root.

Produces llms.txt (a short index) and llms-full.txt (the canonical docs
concatenated into one file) from the documentation sources named below. The
files are artifacts, not manuscripts: edit this generator and regenerate them,
rather than patching the outputs.

WHY PYTHON (issue #1888, docs/CI_GATES.md): Stdlib only — no pip, no network,
no dotnet. This is a document generator that runs where there is no .NET SDK
and no built solution, exactly like the other document tools under tools/.
It does not call dotnet and does not measure time.

Usage:
  python3 tools/gen-llms.py           # write both files
  python3 tools/gen-llms.py --check   # exit 1 if a committed file is stale

The --check mode is for humans and can be wired into CI later; it is not part
of the gate set, so it has no floor, baseline, or self-test of its own.

Exit codes: 0 = written / up to date, 1 = stale output or missing source,
2 = bad invocation.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# (title, repository-relative path, one-line description). The order is the
# reading order an agent should follow, not an alphabetical sort.
INDEX_ENTRIES = [
    ("README", "README.md", "What Harbor is, how to install it, and the CLI surface."),
    ("Getting started", "docs/GETTING_STARTED.md", "First session, provider setup, and the REPL."),
    ("Contributing", "CONTRIBUTING.md", "How to propose and land a change."),
    ("Agent guide", "AGENTS.md", "Operational guide for AI agents, with the full decision tree."),
    ("Code conventions", "CLAUDE.md", "Naming, layering, and the code review checklist."),
    ("Architecture", "docs/ARCHITECTURE.md", "Concrete code flow, sequence diagrams, and the agent loop."),
    ("Architecture layers", "docs/ARCHITECTURE_LAYERS.md", "The Clean/Hexagonal/Onion layering rules and the reference matrix."),
    ("Development workflow", "docs/DEVELOPMENT.md", "Build, per-project tests, docs checks, and debugging recipes."),
    ("Patterns", "docs/PATTERNS.md", "Nine repository patterns with real code."),
    ("Antipatterns", "docs/ANTIPATTERNS.md", "Forty forbidden patterns with before/after code."),
    ("Examples", "docs/EXAMPLES.md", "Task-oriented recipes: tools, providers, agents, TUI views, permissions."),
    ("Tools catalog", "docs/TOOLS_CATALOG.md", "Every builtin tool's arguments, examples, and design walkthrough."),
    ("Plugin development", "docs/PLUGIN_DEVELOPMENT.md", "Write a DLL or C#-source plugin; the available plugin seams."),
    ("Plugin system", "docs/PLUGIN_SYSTEM.md", "Caching, debugging, and security of the plugin host."),
    ("Component catalog", "docs/COMPONENT_CATALOG.md", "Reusable UI components across Avalonia, Blazor, and WPF."),
    ("CI gates", "docs/CI_GATES.md", "The table of every CI gate and why each is a stdlib python script."),
    ("Benchmarks", "docs/BENCHMARKS.md", "Measured numbers and the methodology behind them."),
    ("Roadmap", "docs/ROADMAP.md", "Priorities, current state, and the technical-debt backlog."),
    ("Session format", "docs/SESSION_FORMAT.md", "The JSONL session schema and storage backends."),
    ("E2E testing", "docs/E2E_TESTING.md", "Full-pipeline tests against the Kilocode free model."),
    ("Evals", "docs/EVALS.md", "Task-solving quality runs and their fixtures."),
]

# The documents concatenated into llms-full.txt. Kept narrower than the whole
# docs/ tree on purpose: archived sprint notes, specs, and audit snapshots are
# dated records, not the current product documentation.
FULL_SOURCES = [
    "README.md",
    "CONTRIBUTING.md",
    "SECURITY.md",
    "AGENTS.md",
    "CLAUDE.md",
    "docs/GETTING_STARTED.md",
    "docs/ARCHITECTURE.md",
    "docs/ARCHITECTURE_LAYERS.md",
    "docs/DEVELOPMENT.md",
    "docs/PATTERNS.md",
    "docs/ANTIPATTERNS.md",
    "docs/EXAMPLES.md",
    "docs/TOOLS_CATALOG.md",
    "docs/PLUGIN_DEVELOPMENT.md",
    "docs/PLUGIN_SYSTEM.md",
    "docs/COMPONENT_CATALOG.md",
    "docs/CONFIGURATION.md",
    "docs/SESSION_FORMAT.md",
    "docs/CI_GATES.md",
    "docs/BENCHMARKS.md",
    "docs/ROADMAP.md",
    "docs/E2E_TESTING.md",
    "docs/EVALS.md",
    ".harbor/skills/harbor-dev/SKILL.md",
]

GENERATOR = "tools/gen-llms.py"


def repo_root() -> Path:
    """The directory that holds tools/, src/, and the generated files."""
    return Path(__file__).resolve().parent.parent


def build_index() -> str:
    lines = [
        "# Harbor",
        "",
        "> Harbor is a modular .NET 10 AI coding harness. Every concern sits "
        "behind an interface, the core is NativeAOT-ready, and extensions are "
        "plugins. This is a short index for agents; the full text is in "
        "llms-full.txt.",
        "",
        f"> Generated by `{GENERATOR}`. Do not edit this file by hand.",
        "",
        "## Read first",
        "",
    ]
    for title, rel, desc in INDEX_ENTRIES[:6]:
        lines.append(f"- [{title}]({rel}): {desc}")
    lines += ["", "## Architecture and development", ""]
    for title, rel, desc in INDEX_ENTRIES[6:15]:
        lines.append(f"- [{title}]({rel}): {desc}")
    lines += ["", "## Reference", ""]
    for title, rel, desc in INDEX_ENTRIES[15:]:
        lines.append(f"- [{title}]({rel}): {desc}")
    lines += [
        "",
        "## Full text",
        "",
        "- [llms-full.txt](llms-full.txt): the canonical documents above, "
        "concatenated into one file for agents that cannot follow links.",
        "- [harbor-dev skill](.harbor/skills/harbor-dev/SKILL.md): an in-repo "
        "agent skill for working on Harbor itself.",
        "",
    ]
    return "\n".join(lines)


def build_full(root: Path) -> str:
    lines = [
        "# Harbor full documentation",
        "",
        f"> Generated by `{GENERATOR}` from the sources listed below. For a "
        "short index, see llms.txt. Each source is reproduced verbatim between "
        "its BEGIN and END markers so its provenance stays visible.",
        "",
        "Sources, in order:",
        "",
    ]
    lines += [f"- {rel}" for rel in FULL_SOURCES]
    lines.append("")
    for rel in FULL_SOURCES:
        lines += ["---", "", f"<!-- BEGIN SOURCE: {rel} -->", ""]
        lines.append(read_source(root, rel).rstrip("\n"))
        lines += ["", f"<!-- END SOURCE: {rel} -->", ""]
    return "\n".join(lines)


def read_source(root: Path, rel: str) -> str:
    path = root / rel
    if not path.is_file():
        raise FileNotFoundError(rel)
    return path.read_text(encoding="utf-8")


def generate(root: Path) -> dict[str, str]:
    # Fail before writing anything if a named source has gone missing: a
    # document that was renamed must be fixed in this list, not silently
    # dropped from the generated output.
    for rel in FULL_SOURCES:
        read_source(root, rel)
    return {"llms.txt": build_index(), "llms-full.txt": build_full(root)}


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if a committed output differs from generated text")
    args = parser.parse_args(argv)
    root = repo_root()
    try:
        outputs = generate(root)
    except (FileNotFoundError, UnicodeDecodeError) as exc:
        print(f"cannot generate: {exc}", file=sys.stderr)
        return 1
    if args.check:
        stale = []
        for name, text in outputs.items():
            path = root / name
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        if stale:
            print("stale generated files: " + ", ".join(stale)
                  + f" (run python3 {GENERATOR})", file=sys.stderr)
            return 1
        print("OK: llms.txt and llms-full.txt are up to date.")
        return 0
    for name, text in outputs.items():
        (root / name).write_text(text, encoding="utf-8")
        print(f"wrote {name} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
