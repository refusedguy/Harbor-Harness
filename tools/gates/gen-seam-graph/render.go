package genseamgraph

// render.go — the document. A transliteration of the `render` function of
// tools/gen-seam-graph.py, line for line, so that the output is byte
// identical to the committed docs/SEAM_GRAPH.md.

import (
	"fmt"
	"path/filepath"
	"sort"
	"strings"
)

const topSeams = 40

// cell is a table cell: the values, comma separated, truncated with a count.
func cell(values []string, limit int) string {
	if len(values) == 0 {
		return "none"
	}
	if len(values) <= limit {
		return strings.Join(values, ", ")
	}
	return strings.Join(values[:limit], ", ") + fmt.Sprintf(" (+%d more)", len(values)-limit)
}

// link is a markdown link to a repository file, relative to docs/.
func link(rel string) string {
	return "[`" + rel + "`](../" + rel + ")"
}

// labels are display names for types, disambiguated where the simple name is
// not unique.
type labels struct {
	byName        map[string][]*typeDecl
	byNameProject map[string]int
}

func newLabels(decls []*typeDecl) *labels {
	l := &labels{byName: map[string][]*typeDecl{}, byNameProject: map[string]int{}}
	for _, d := range decls {
		l.byName[d.name] = append(l.byName[d.name], d)
	}
	for name, group := range l.byName {
		for _, d := range group {
			l.byNameProject[name+"\x00"+d.project()]++
		}
	}
	return l
}

func (l *labels) label(decl *typeDecl) string {
	group := l.byName[decl.name]
	if len(group) <= 1 {
		return decl.name
	}
	if l.byNameProject[decl.name+"\x00"+decl.project()] == 1 {
		return decl.name + " (" + decl.project() + ")"
	}
	return decl.name + " (" + filepath.Base(decl.rel()) + ")"
}

func isProduct(rel string) bool {
	return strings.HasPrefix(rel, "src/") || strings.HasPrefix(rel, "apps/")
}

func render(g *graph) string {
	axes := g.axes()
	lbl := newLabels(g.decls)
	var out []string
	w := func(s string) { out = append(out, s) }

	w("# Seam graph")
	w("")
	w("Generated by [`tools/bin/harbor-gates-linux-x64 gen-seam-graph`](../tools/bin/harbor-gates-linux-x64). Do not edit by hand. Regenerate with:")
	w("")
	w("```")
	w("tools/bin/harbor-gates-linux-x64 gen-seam-graph --write")
	w("```")
	w("")
	w("Every row below is read out of the C# sources at the moment of generation. Nothing here is a hand-maintained claim, which is the point: the graph cannot drift away from the code, and the CI gate fails the build when it does.")
	w("")
	w("The graph answers four questions about a seam: **who implements it**, **who extends what implements it**, **who consumes it**, and **who is registered in the container**. It also reports the question nobody asks, which is the one that finds bugs: **where the seam is bypassed**, the places that name the concrete type where the interface was the contract.")
	w("")

	// ---- 1. axes -------------------------------------------------------
	w("## 1. Extension axes")
	w("")
	w("The axes of plugin extension, read out of " + link(axisRegistry) + ", the single registry the architecture rule `ExtensionAxisRegistrationRule` grades the code against. Each axis has two halves: a **marker** a plugin implements, and a **door** on " + link(loadHostInterface) + " that receives the contribution.")
	w("")
	w("**In-tree implementers** are the classes under `src/` and `apps/` that implement the marker. **Out-of-tree implementers** are the ones under `tests/` and `samples/`, the doubles and the sample plugins.")
	w("")
	w("| Axis | Marker | Door | In-tree implementers | Out-of-tree implementers | Marker dispatched at | Door called at |")
	w("|---|---|---|---|---|---|---|")
	for _, ax := range axes {
		product := make([]string, 0, len(ax.markerImplsProduct))
		for _, d := range ax.markerImplsProduct {
			product = append(product, "`"+lbl.label(d)+"`")
		}
		outside := make([]string, 0, len(ax.markerImplsOutside))
		for _, d := range ax.markerImplsOutside {
			outside = append(outside, "`"+lbl.label(d)+"`")
		}
		dispatch := make([]string, 0, len(ax.dispatchSites))
		for _, s := range ax.dispatchSites {
			dispatch = append(dispatch, s.rel+":"+itoa(s.line))
		}
		called := make([]string, 0, len(ax.doorSites))
		for _, s := range ax.doorSites {
			called = append(called, s.rel+":"+itoa(s.line))
		}
		w("| " + ax.marker + " | `" + ax.marker + "` | `" + ax.door + "` | " + cell(product, 6) + " | " + cell(outside, 6) + " | " + cell(dispatch, 2) + " | " + cell(called, 2) + " |")
	}
	w("")

	inTreeMarkers := 0
	for _, ax := range axes {
		inTreeMarkers += len(ax.markerImplsProduct)
	}
	var uncalledDoors []string
	for _, ax := range axes {
		if len(ax.doorSites) == 0 {
			uncalledDoors = append(uncalledDoors, ax.door)
		}
	}
	var facts []string
	if inTreeMarkers == 0 {
		facts = append(facts, "**no in-tree class implements any axis marker**. The markers are extension points, so the only implementers are out-of-tree plugins, the samples and the test doubles")
	} else {
		facts = append(facts, fmt.Sprintf("**%d in-tree class(es) implement an axis marker**", inTreeMarkers))
	}
	if len(uncalledDoors) > 0 {
		var quoted []string
		for _, d := range uncalledDoors {
			quoted = append(quoted, "`"+d+"`")
		}
		facts = append(facts, "**these doors are never called on a receiver**: "+strings.Join(quoted, ", "))
	} else {
		facts = append(facts, "**every door is called on a receiver** inside the product, which is the half the architecture rule grades")
	}
	w("Two facts a reader would otherwise have to dig for. First, " + facts[0] + ". Second, " + facts[1] + ".")
	w("")

	// ---- 2. route matrix -----------------------------------------------
	if len(g.routeRows) > 0 {
		w("### 1.1 Which route carries which axis")
		w("")
		w("A **route** is the place a plugin's contribution lands: an implementation of `IPluginLoadHost` the product declares a route for. What the route does with each axis is DECLARED in " + link(routeAxisRegistry) + " since #1723, and the table reads that file for the verdict and the reason.")
		w("")
		w("The **observed** column is the other half: what the route's own door body does, read from the source. The two columns are printed side by side because the difference between them is the defect the architecture rule grades, and a reader of the graph is here to see it.")
		w("")
		w("| Route | Axis | Door | Declared | Observed | Reason |")
		w("|---|---|---|---|---|---|")
		for _, row := range g.routeRows {
			declared := row.declared
			switch declared {
			case "Carried":
				declared = "carried"
			case "Refused":
				declared = "refused"
			case "ClosedSeam":
				declared = "closed seam"
			}
			w("| `" + row.route + "` | `" + row.marker + "` | `" + row.door + "` | " + declared + " | " + strings.ToLower(row.observed) + " | " + row.reason + " |")
		}
		w("")
		routeSet := map[string]bool{}
		for _, row := range g.routeRows {
			routeSet[row.route] = true
		}
		for _, route := range sortedKeys(routeSet) {
			var rows []*routeAxisRow
			for _, r := range g.routeRows {
				if r.route == route {
					rows = append(rows, r)
				}
			}
			carried, refused, closed := 0, 0, 0
			for _, r := range rows {
				switch r.declared {
				case "Carried":
					carried++
				case "Refused":
					refused++
				case "ClosedSeam":
					closed++
				}
			}
			w("- `" + route + "` carries " + itoa(carried) + " of the " + itoa(len(rows)) + " axes, refuses " + itoa(refused) + " and closes " + itoa(closed) + ".")
		}
		w("")
		var mismatches []*routeAxisRow
		for _, row := range g.routeRows {
			if !row.agrees() {
				mismatches = append(mismatches, row)
			}
		}
		if len(mismatches) > 0 {
			w("The declared verdict and the observed behaviour disagree on " + itoa(len(mismatches)) + " row(s):")
			w("")
			for _, row := range mismatches {
				w("- `" + row.route + "` / `" + row.door + "`: declared " + strings.ToLower(row.declared) + ", observed " + strings.ToLower(row.observed) + " (" + row.observedNote + ")")
			}
			w("")
		}
		if len(g.otherHosts) > 0 {
			w("The other implementations of `IPluginLoadHost` in the product are not routes: the registry does not name them, and the graph does not pretend otherwise. They are still answers to the same doors, so a reader looking for who answers a given door has to see them.")
			w("")
			w("| Implementation | What its doors do | Where |")
			w("|---|---|---|")
			for _, oh := range g.otherHosts {
				line := "| `" + lbl.label(oh.decl) + "` | " + strings.ToLower(oh.kinds) + " | " + link(oh.decl.rel())
				if oh.note != "" {
					line += " (" + oh.note + ")"
				}
				w(line + " |")
			}
			w("")
		}
	}

	// ---- 3. mermaid ----------------------------------------------------
	w("### 1.2 The axes as a graph")
	w("")
	w("```mermaid")
	w("graph LR")
	w("  subgraph plugin[\"A plugin implements\"]")
	for _, ax := range axes {
		w("    " + ax.marker + "[\"" + ax.marker + "\"]")
	}
	w("  end")
	w("  subgraph registrar[\"PluginRegistrar dispatches\"]")
	for _, ax := range axes {
		w("    d_" + ax.marker + "[\"" + ax.door + "\"]")
	}
	w("  end")
	for _, ax := range axes {
		w("  " + ax.marker + " --> d_" + ax.marker)
	}
	w("```")
	w("")

	// ---- 4. core seams -------------------------------------------------
	var interfaces []*typeDecl
	for _, d := range g.decls {
		if d.kind == "interface" && strings.HasPrefix(d.rel(), "src/") {
			interfaces = append(interfaces, d)
		}
	}
	type seamRow struct {
		decl         *typeDecl
		impls        []*typeDecl
		productImpls []*typeDecl
		consumers    map[string][]site
		regs         []registration
		bypasses     []bypass
	}
	var seamRows []*seamRow
	for _, decl := range interfaces {
		impls := g.implementers(decl.name)
		consumers := g.consumers(decl.name)
		regs := g.registrationsFor(decl.name)
		var bypasses []bypass
		for _, b := range g.bypasses {
			if b.seam == decl.name {
				bypasses = append(bypasses, b)
			}
		}
		var productImpls []*typeDecl
		for _, i := range impls {
			if isProduct(i.rel()) {
				productImpls = append(productImpls, i)
			}
		}
		seamRows = append(seamRows, &seamRow{decl, impls, productImpls, consumers, regs, bypasses})
	}
	sort.SliceStable(seamRows, func(i, j int) bool {
		ai := len(seamRows[i].productImpls) + len(seamRows[i].consumers)
		aj := len(seamRows[j].productImpls) + len(seamRows[j].consumers)
		if ai != aj {
			return ai > aj
		}
		return seamRows[i].decl.name < seamRows[j].decl.name
	})

	w("## 2. Core seams")
	w("")
	w("Every interface declared under `src/`, ranked by how much of the product touches it. **Implementations** counts the classes that implement it, directly or through a base class; the in-tree ones come first and the out-of-tree ones (doubles, samples) after a `/`. **Consumers** counts the files that name it, excluding the files that only put it in a base list. **Registered** is the container registration, if the seam is resolved from the DI graph. **Bypasses** counts the places that name the concrete type where the interface was the contract.")
	w("")
	w("The table shows the " + itoa(topSeams) + " seams with the most in-tree implementations and consumers, out of " + itoa(len(interfaces)) + " interfaces declared under `src/`. The rest are in `--report`.")
	w("")
	w("| Seam | Declared in | Implementations | Consumer files | Registered as | Bypasses |")
	w("|---|---|---|---|---|---|")
	limit := topSeams
	if len(seamRows) < limit {
		limit = len(seamRows)
	}
	for _, row := range seamRows[:limit] {
		productNames := make([]string, 0, len(row.productImpls))
		for _, i := range row.productImpls {
			productNames = append(productNames, "`"+lbl.label(i)+"`")
		}
		var otherNames []string
		for _, i := range row.impls {
			if !isProduct(i.rel()) {
				otherNames = append(otherNames, "`"+lbl.label(i)+"`")
			}
		}
		implCell := cell(productNames, 5)
		if len(otherNames) > 0 {
			implCell += " / " + cell(otherNames, 3)
		}
		regTexts := make([]string, 0, len(row.regs))
		for _, r := range row.regs {
			if r.impl != "" {
				regTexts = append(regTexts, "`"+r.impl+"`")
			} else {
				regTexts = append(regTexts, "a factory")
			}
		}
		regText := cell(regTexts, 2)
		w("| `" + lbl.label(row.decl) + "` | " + link(row.decl.rel()) + " | " + implCell + " | " + itoa(len(row.consumers)) + " | " + regText + " | " + itoa(len(row.bypasses)) + " |")
	}
	w("")

	// ---- 5. detail -----------------------------------------------------
	w("## 3. Three seams in detail")
	w("")
	w("The table above is a census. These are the seams a reader most often has to reason about, and the graph says things about them that are not visible by reading one file.")
	w("")
	for _, seam := range []string{"IToolRegistry", "ILlmClient", "IPluginHost"} {
		var decl *typeDecl
		for _, d := range interfaces {
			if d.name == seam {
				decl = d
				break
			}
		}
		if decl == nil {
			continue
		}
		impls := g.implementers(seam)
		consumers := g.consumers(seam)
		regs := g.registrationsFor(seam)
		var bypasses []bypass
		for _, b := range g.bypasses {
			if b.seam == seam {
				bypasses = append(bypasses, b)
			}
		}
		var productImpls, otherImpls []*typeDecl
		for _, i := range impls {
			if isProduct(i.rel()) {
				productImpls = append(productImpls, i)
			} else {
				otherImpls = append(otherImpls, i)
			}
		}
		w("### `" + seam + "`")
		w("")
		w("Declared in " + link(decl.rel()) + ".")
		w("")
		w("- **In-tree implementations** (" + itoa(len(productImpls)) + "):")
		if len(productImpls) > 0 {
			for _, impl := range productImpls {
				w("  - `" + lbl.label(impl) + "`, " + link(impl.rel()))
			}
		} else {
			w("  - **none**")
		}
		w("- **Out-of-tree implementations** (" + itoa(len(otherImpls)) + "):")
		if len(otherImpls) > 0 {
			for _, impl := range otherImpls {
				w("  - `" + lbl.label(impl) + "`, " + link(impl.rel()))
			}
		} else {
			w("  - **none**")
		}
		projectSet := map[string]bool{}
		for rel := range consumers {
			projectSet[g.projectOf(rel)] = true
		}
		projects := sortedKeys(projectSet)
		shownProjects := projects
		if len(shownProjects) > 10 {
			shownProjects = shownProjects[:10]
		}
		w("- **Named by** " + itoa(len(consumers)) + " file(s) in " + itoa(len(projects)) + " project(s): " + strings.Join(shownProjects, ", "))
		if len(regs) > 0 {
			var parts []string
			for _, r := range regs {
				implText := "a factory"
				if r.impl != "" {
					implText = "`" + r.impl + "`"
				}
				parts = append(parts, "`"+r.service+"` → "+implText+" ("+r.lifetime+", "+link(r.file)+")")
			}
			w("- **Registered in the container**: " + strings.Join(parts, "; "))
		} else {
			w("- **Registered in the container**: **no DI registration**")
		}
		var constructions, signatures []bypass
		for _, b := range bypasses {
			switch b.form {
			case "construction":
				constructions = append(constructions, b)
			case "signature":
				signatures = append(signatures, b)
			}
		}
		w("- **Bypassed**: " + itoa(len(constructions)) + " direct construction(s) of the concrete type, " + itoa(len(signatures)) + " signature(s) naming the concrete type where the interface was the contract:")
		all := append(append([]bypass{}, constructions...), signatures...)
		shown := all
		if len(shown) > 12 {
			shown = shown[:12]
		}
		if len(shown) > 0 {
			for _, b := range shown {
				w("  - `" + b.concrete + "` instead of `" + seam + "`, " + b.form + " at " + link(b.file) + ":" + itoa(b.line))
			}
			if len(all) > len(shown) {
				w("  - … and " + itoa(len(all)-len(shown)) + " more")
			}
		} else {
			w("  - **none**")
		}
		w("")
	}

	// ---- 6. holes ------------------------------------------------------
	w("## 4. Holes")
	w("")
	w("What the graph finds that reading the code does not: interfaces with no implementation, seams nobody resolves from the container, and implementations nobody consumes.")
	w("")
	var empty []*typeDecl
	for _, d := range interfaces {
		if len(g.implementers(d.name)) == 0 && len(g.consumers(d.name)) > 0 {
			empty = append(empty, d)
		}
	}
	if len(empty) > 0 {
		var names []string
		for _, d := range empty {
			names = append(names, "`"+d.name+"`")
		}
		w("- **" + itoa(len(empty)) + " interface(s) declared under `src/` are named somewhere but have no implementation**: " + strings.Join(names, ", "))
	} else {
		w("- No interface under `src/` is named without being implemented.")
	}
	var unregistered []*typeDecl
	for _, d := range interfaces {
		if len(g.implementers(d.name)) > 0 && len(g.registrationsFor(d.name)) == 0 {
			unregistered = append(unregistered, d)
		}
	}
	var unregNames []string
	for _, d := range unregistered {
		if len(unregNames) == 20 {
			break
		}
		unregNames = append(unregNames, "`"+d.name+"`")
	}
	ellipsis := ""
	if len(unregistered) > 20 {
		ellipsis = " …"
	}
	w("- **" + itoa(len(unregistered)) + " seam(s) with an implementation have no container registration**: " + strings.Join(unregNames, ", ") + ellipsis)
	w("  That is a census of the `AddSingleton<T>` calls, not a verdict on reachability: a seam can also be resolved through a registry rather than the container. `ILlmClient` is reached through `IProviderRegistry`, not through DI.")
	var silent []string
	for _, row := range g.routeRows {
		if row.observed == "SILENT" {
			silent = append(silent, "`"+row.door+"` via `"+row.route+"`")
		}
	}
	if len(silent) > 0 {
		w("- **" + itoa(len(silent)) + " door/route pair(s) answer `Result.Success` without registering anything**: " + strings.Join(silent, ", "))
	} else {
		w("- No door of a declared route answers `Result.Success` without registering anything (the #1758 shape).")
	}
	var mismatches []*routeAxisRow
	for _, row := range g.routeRows {
		if !row.agrees() {
			mismatches = append(mismatches, row)
		}
	}
	if len(mismatches) > 0 {
		var parts []string
		for _, row := range mismatches {
			parts = append(parts, "`"+row.route+"` / `"+row.door+"` ("+strings.ToLower(row.declared)+" vs "+strings.ToLower(row.observed)+")")
		}
		w("- **" + itoa(len(mismatches)) + " declared route verdict(s) disagree with what the door does**: " + strings.Join(parts, ", "))
	} else {
		w("- Every declared route verdict agrees with what the route's door body does.")
	}
	w("")

	// ---- 7. limits -----------------------------------------------------
	w("## 5. What this graph does not see")
	w("")
	w("A graph that hides its own blind spots is a decoration. These are the gaps, and they are gaps of a TEXT SCAN, not of the code:")
	w("")
	w("- **DI registrations written without a type argument** (`services.AddSingleton(sp => new Foo())`) are invisible: the service type is inferred by the compiler, and the scan has no compiler.")
	w("- **Bypasses in a signature** are a heuristic: a type name followed by a member name is matched by shape, not by a parsed type. The count is an upper bound.")
	w("- **`contrib/` is not scanned.** It is not compiled by CI and the owner marked it unmaintained, so a seam that only exists there is not a seam of this product.")
	w("- **Extension methods are not classified.** A static class with `this` in its first parameter is a seam to read, and the scan does not say so.")
	w("- **Reflection-reached seams are not counted as consumed.** A type resolved by name at run time has no textual mention to find.")
	w("- **A simple name that two namespaces share is disambiguated in the labels, but the EDGES are resolved per namespace.** An ambiguous name used in a base list resolves to nothing rather than to a guess.")
	w("- **The route registry pairs a route with its host by NAME.** The registry declares `McpStdioRouteId` and `McpStdioHostType` as two constants, and the graph pairs them because the names share a prefix. A route whose id and host type do not share one is read as a route with no host, and the table says so.")
	w("- **The type graph is one level of inheritance deep for the `extends` edges, and closed transitively for the `implements` edges.** A base class reached only through an alias is not seen.")
	w("")
	w("## 6. How to regenerate and to check")
	w("")
	w("```")
	w("tools/bin/harbor-gates-linux-x64 gen-seam-graph --write     # regenerate this file")
	w("tools/bin/harbor-gates-linux-x64 gen-seam-graph --check     # fail if this file is stale")
	w("tools/bin/harbor-gates-linux-x64 gen-seam-graph --report    # the numbers, on stdout")
	w("tools/bin/harbor-gates-linux-x64 gen-seam-graph --self-test # prove the checker can fail")
	w("```")
	w("")
	return strings.Join(out, "\n")
}
